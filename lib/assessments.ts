export function scoreAssessment(test:AssessmentDefinition,answers:number[]):Record<string,number>{
 if(!validAnswers(answers,test))throw new Error('Invalid assessment answers');
 if(test.noTotal||test.respondent==='external')return {};
 if(test.scoreItems){const values=answers.map((a,i)=>test.itemScores?.[i]?.[a]??a);return Object.fromEntries(Object.entries(test.scoreItems).map(([key,items])=>[key,items.reduce((sum,n)=>sum+values[n-1],0)]));}
 if(test.key===DASS42.key)return scoreDass42(answers);
 if([PHQ9.key,GAD7.key,MFQ20.key].includes(test.key))return {total:answers.reduce((sum,n)=>sum+n,0)};
 if(test.key===POMS38.key){
  let positive=0,negative=0;
  answers.forEach((n,i)=>{if(POMS_POSITIVE_SOURCE_ITEMS.includes(POMS_SOURCE_ITEMS[i]))positive+=n;else negative+=n;});
  return {negative,positive,disturbance:negative-positive};
 }
 throw new Error('Unknown assessment scoring');
}

export function matches(condition:FormCondition,values:Record<string,unknown>):boolean{
 return Object.entries(condition).every(([key,value])=>key==='any'? (value as FormCondition[]).some(c=>matches(c,values)):key==='all'?(value as FormCondition[]).every(c=>matches(c,values)):typeof value==='number'?values[key]===value:typeof values[key]==='number'&&(values[key] as number)>(value as {greaterThan:number}).greaterThan);
}
export function fieldVisible(f:AssessmentField,values:Record<string,unknown>){return !(f.skipWhen&&matches(f.skipWhen,values))&&(!(f.visibleWhen??f.requiredWhen)||matches((f.visibleWhen??f.requiredWhen)!,values));}
export function validateFields(test:AssessmentDefinition,input:unknown):Record<string,string|number>{
 const fields=test.fields??[];
 if(!input||typeof input!=='object'||Array.isArray(input))throw new Error('Заполните дополнительные поля формы');
 const values=input as Record<string,unknown>,out:Record<string,string|number>={};
 if(Object.keys(values).some(k=>!fields.some(f=>f.id===k)))throw new Error('Неизвестное поле формы');
 for(const f of fields){const v=values[f.id];if(!fieldVisible(f,values)){if(v!==undefined&&v!==null&&v!=='')throw new Error('Ответ в пропущенном разделе: '+f.title);continue;}
  if(v===undefined||v===null||v===''){if(f.required)throw new Error('Заполните: '+f.title);continue;}
  if(f.type==='choice'){if(!f.options?.some(o=>o.value===v))throw new Error('Выберите ответ: '+f.title);}
  else if(f.type==='integer'||f.type==='number'){if(typeof v!=='number'||!Number.isFinite(v)||(f.type==='integer'&&!Number.isInteger(v))||v<(f.min??0)||v>(f.max??100000))throw new Error('Проверьте значение: '+f.title);}
  else if(typeof v!=='string'||v.length>2000||(f.type==='date'&&(!/^\d{4}-\d{2}-\d{2}$/.test(v)||!Number.isFinite(Date.parse(v))||new Date(v).toISOString().slice(0,10)!==v||v>new Date().toISOString().slice(0,10))))throw new Error('Проверьте поле: '+f.title);
  if(typeof v==='string'&&!v.trim()){if(f.required)throw new Error('Заполните: '+f.title);continue;}
  out[f.id]=typeof v==='string'?v.trim():v as number;
 }
 if(test.key==='cssrs_lifetime'&&out.most_severe_type!==undefined){const highest=Math.max(0,...[1,2,3,4,5].filter(n=>out['ideation'+n]===1));if(out.most_severe_type!==highest)throw new Error('Наиболее опасная идея должна соответствовать ответам в первом разделе.');}
 return out;
}
