const base = process.argv[2] || 'http://127.0.0.1:8787';
const stamp = crypto.randomUUID(), password = 'Test-' + crypto.randomUUID();
let checks = 0;
async function request(path, cookie, method = 'GET', body, expected = 200) {
  const r = await fetch(base + '/api/' + path, { method, headers: { Origin: base, ...(cookie ? { Cookie: cookie } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, body: body ? JSON.stringify(body) : undefined });
  const json = await r.json();
  assert.equal(r.status, expected, `${method} ${path}: ${JSON.stringify(json)}`);
  assert.equal(r.headers.get('cache-control'), 'no-store'); checks++;
  return { ...json, cookie: r.headers.get('set-cookie')?.split(';')[0] };
}
