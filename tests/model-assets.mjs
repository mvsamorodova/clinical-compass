import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFile} from 'node:fs/promises';
import {gzipSync} from 'node:zlib';
const require=createRequire(import.meta.url);
const esbuild=require(require.resolve('esbuild',{paths:[require.resolve('wrangler/package.json')]}));
const built=await esbuild.build({entryPoints:['lib/model-assets-api.ts'],bundle:true,platform:'node',format:'esm',write:false});
const {modelAssetsApi}=await import('data:text/javascript;base64,'+Buffer.from(built.outputFiles[0].contents).toString('base64'));
const manifest=JSON.parse(await readFile('lib/gigaam-model-manifest.json','utf8')),chunk=manifest.chunks[0];
const bytes=await readFile(process.argv[2]||'outputs/gigaam-model-source-backup/weights-00.bin');
const objects=new Map();let puts=0;
const bucket={head:async k=>objects.get(k)||null,get:async k=>{const n=objects.get(k);return n?{...n,body:new Blob([n.bytes]).stream()}:null;},put:async(k,b,options)=>{puts++;objects.set(k,{bytes:b,size:b.length,customMetadata:options.customMetadata});}};
const path=chunk.url.replace('/api/','').split('/'),testKey='local-test-upload-key';
async function call(method='GET',data,key=testKey,route=path,gzip=false){const req=new Request('https://unit.invalid/api/'+route.join('/'),{method,headers:{'X-Model-Upload-Key':key,...(gzip?{'X-Model-Encoding':'gzip'}:{})},...(data?{body:data}:{})});return modelAssetsApi(req,route,bucket,testKey);}
const fails=(fn,status)=>assert.rejects(fn,e=>e.status===status);
await fails(()=>call(),503);
await fails(()=>call('PUT',bytes,'wrong'),403);assert.equal(puts,0);
await fails(()=>call('PUT',new Uint8Array(9)),400);
await fails(()=>call('PUT',new Uint8Array(chunk.bytes+1025)),413);
await fails(()=>call('GET',undefined,testKey,['model-assets','wrong','weights-00.bin']),404);
await fails(()=>call('GET',undefined,testKey,['model-assets',path[1],'../../voice/private']),404);
await fails(()=>call('GET',undefined,testKey,[...path,'extra']),404);
assert.equal(await modelAssetsApi(new Request('https://unit.invalid/api/voice'),['voice'],bucket,testKey),null);
let r=await call('PUT',gzipSync(bytes),testKey,path,true);assert.equal(r.status,200);assert.equal((await r.json()).sha256,chunk.sha256);assert.equal(puts,1);
r=await call();assert.equal(r.status,200);assert.equal(r.headers.get('cache-control'),'public, max-age=31536000, immutable');assert.deepEqual(Buffer.from(await r.arrayBuffer()),bytes);
await call('PUT',bytes);assert.equal(puts,1);
const disabled=new Request('https://unit.invalid'+chunk.url,{method:'PUT',headers:{'X-Model-Upload-Key':testKey},body:bytes});
await fails(()=>modelAssetsApi(disabled,path,bucket,undefined),403);
r=await modelAssetsApi(new Request('https://unit.invalid'+chunk.url),path,bucket,undefined);assert.equal(r.status,200);await r.arrayBuffer();
console.log('PASS model asset checks: allowlist, private-key isolation, temporary upload key, hash/size, gzip, idempotence, public read, disabled upload.');
