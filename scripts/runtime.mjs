import { mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
process.chdir(root);
process.env.CLOUDFLARE_CF_FETCH_ENABLED ??= 'false';
process.env.WRANGLER_SEND_METRICS ??= 'false';
process.env.WRANGLER_WRITE_LOGS ??= 'false';
process.env.WRANGLER_LOG_PATH ??= path.join(root, '.runtime/logs');
process.env.WRANGLER_REGISTRY_PATH ??= path.join(root, '.runtime/registry');
process.env.MINIFLARE_REGISTRY_PATH ??= path.join(root, '.runtime/registry');
mkdirSync(process.env.WRANGLER_REGISTRY_PATH, { recursive: true });
